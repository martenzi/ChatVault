"""raw/ lifecycle: classify every file under raw/, decide where it belongs, and
(for 00_inbox/) ingest + verify + move it.

Layout (docs/72_PROMPT_raw_inbox_lifecycle_and_backlog_completion.md §A1):

    raw/00_inbox/                      drop anything here
    raw/10_ingested/<platform>/<date>/ verified-ingested files
    raw/20_needs_adapter/              chat-shaped, no adapter claims it
    raw/30_excluded/<reason>/          deliberately not ingested (WHY.md each)
    raw/40_archive/                    original zips, derivative copies
    raw/_STATUS.md                     generated at-a-glance view

A file is never classified by path alone. The order is: tracked by sha256 ->
companion of an ingested export -> content already in the vault -> an adapter
claims it -> chat-shaped but unclaimed -> excluded with a reason.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import sqlite3
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import orjson

from chatvault import adapters, hashing

INBOX = "00_inbox"
INGESTED = "10_ingested"
NEEDS_ADAPTER = "20_needs_adapter"
EXCLUDED = "30_excluded"
ARCHIVE = "40_archive"
LIFECYCLE_DIRS = (INBOX, INGESTED, NEEDS_ADAPTER, EXCLUDED, ARCHIVE)
JUNK_NAMES = {".DS_Store"}
SYSTEM_NAMES = {"_STATUS.md", "_manifest.jsonl", "WHY.md"}  # generated by ChatVault itself
STATUS_FILE = "_STATUS.md"


@dataclass
class Entry:
    path: Path
    rel: str  # relative to raw/
    bucket: str  # tracked | companion | in_vault | candidate | needs_adapter | excluded | archive | junk
    reason: str = ""
    platform: str | None = None
    date: str | None = None
    dest_rel: str | None = None  # relative to raw/; None = stays put
    evidence: str = ""


# ───────────────────────────── helpers ─────────────────────────────


def _is_lifecycle_path(rel: str) -> str | None:
    first = rel.split("/", 1)[0]
    return first if first in LIFECYCLE_DIRS else None


def artifact_bundle_sha(artifact_json: Path) -> str:
    """Same composite hash ingest uses for artifacts/<id>/ bundles."""
    h = hashlib.sha256()
    for p in sorted(x for x in artifact_json.parent.rglob("*") if x.is_file() and x.name != ".DS_Store"):
        h.update(str(p.relative_to(artifact_json.parent)).encode())
        h.update(hashing.file_sha256(p).encode())
    return h.hexdigest()


_WORD = re.compile(r"[^\W_]+")


def _string_leaves(obj, out: list[str], minlen: int = 80, cap: int = 4000) -> None:
    if len(out) >= cap:
        return
    if isinstance(obj, str):
        if len(obj) >= minlen:
            out.append(obj)
    elif isinstance(obj, dict):
        for v in obj.values():
            _string_leaves(v, out, minlen, cap)
    elif isinstance(obj, list):
        for v in obj:
            _string_leaves(v, out, minlen, cap)


def content_in_vault(conn: sqlite3.Connection, path: Path, samples: int = 10) -> tuple[bool, str]:
    """Is the text of this JSON file already searchable in the vault? Takes up
    to `samples` long string leaves spread across the file, looks each up as a
    7-word phrase in blocks_fts, and requires >= 60% hits (and >= 2 leaves).
    Immune to file moves and renames; a title match is not evidence."""
    try:
        if path.stat().st_size > 30_000_000:
            return False, "too large to test"
        data = orjson.loads(path.read_bytes())
    except (OSError, ValueError):
        return False, "not json"
    leaves: list[str] = []
    _string_leaves(data, leaves)
    if len(leaves) < 2:
        return False, "fewer than 2 long text leaves"
    step = max(1, len(leaves) // samples)
    picked = leaves[::step][:samples]
    hits = tested = 0
    for text in picked:
        words = _WORD.findall(text)
        if len(words) < 9:
            continue
        mid = len(words) // 2
        phrase = " ".join(words[max(0, mid - 3): mid + 4])
        tested += 1
        row = conn.execute(
            "SELECT 1 FROM blocks_fts WHERE blocks_fts MATCH ? LIMIT 1", ('"' + phrase.replace('"', "") + '"',)
        ).fetchone()
        hits += 1 if row else 0
    if tested < 2:
        return False, "fewer than 2 testable leaves"
    return hits / tested >= 0.6, f"{hits}/{tested} text samples found in vault"


def looks_like_chat(path: Path) -> bool:
    """Cheap structural guess: JSON/JSONL carrying role + content-ish keys, or
    a messages/conversations/mapping container. Only used to decide whether an
    unclaimed file is an adapter backlog item or just a file."""
    if path.suffix.lower() not in {".json", ".jsonl"}:
        return False
    try:
        with path.open("rb") as fh:
            head = fh.read(2_000_000)
    except OSError:
        return False
    if b'"role"' in head and any(k in head for k in (b'"content"', b'"text"', b'"parts"', b'"contents"')):
        return True
    return any(k in head for k in (b'"chatSessions"', b'"conversations"', b'"mapping"', b'"messages"'))


# ───────────────────────────── classification ─────────────────────────────


@dataclass
class Index:
    by_sha: dict[str, list[tuple[str, str, str]]]  # sha -> [(platform, adapter, ingested_at)]
    dir_platforms: dict[str, Counter]  # rel dir -> platform counts of tracked files at/below it
    top_platforms: dict[str, Counter]
    top_dates: dict[tuple[str, str], str]  # (top, platform) -> earliest ingest date


def build_index(conn: sqlite3.Connection, raw_dir: Path) -> Index:
    by_sha: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for r in conn.execute("SELECT sha256, platform, adapter, ingested_at FROM source_files"):
        by_sha[r["sha256"]].append((r["platform"], r["adapter"], r["ingested_at"]))
    return Index(by_sha, defaultdict(Counter), defaultdict(Counter), {})


def _tracked_platform(idx: Index, sha: str) -> tuple[str, str] | None:
    rows = idx.by_sha.get(sha)
    if not rows:
        return None
    rows = sorted(rows, key=lambda x: x[2])
    return rows[0][0], rows[0][2][:10]


def classify_tree(conn: sqlite3.Connection, raw_dir: Path, *, only: str | None = None) -> list[Entry]:
    """Classify every file under raw_dir (or only raw_dir/<only>). Read-only."""
    idx = build_index(conn, raw_dir)
    base = raw_dir / only if only else raw_dir
    files = sorted(p for p in base.rglob("*") if p.is_file())
    entries: list[Entry] = []

    # pass 1: tracked by sha (and artifact bundles by composite sha)
    for p in files:
        rel = str(p.relative_to(raw_dir))
        if p.name in JUNK_NAMES or (p.name in SYSTEM_NAMES and (len(Path(rel).parts) == 1 or p.name == "WHY.md")):
            entries.append(Entry(p, rel, "junk", "os metadata / generated by ChatVault"))
            continue
        if p.suffix.lower() == ".zip":
            entries.append(Entry(p, rel, "archive", "original zip"))
            continue
        e = Entry(p, rel, "unresolved")
        sha = hashing.file_sha256(p)
        hit = _tracked_platform(idx, sha)
        if hit is None and p.name != "artifact.json":
            # files inside an ingested artifact bundle are covered by its composite sha
            art = _artifact_parent(p, raw_dir)
            if art is not None and art not in _BUNDLE_CACHE:
                _BUNDLE_CACHE[art] = _tracked_platform(idx, artifact_bundle_sha(art / "artifact.json"))
            hit = _BUNDLE_CACHE.get(art) if art is not None else None
        elif hit is None and p.name == "artifact.json":
            hit = _tracked_platform(idx, artifact_bundle_sha(p))
        if hit:
            e.bucket, e.platform, e.date = "tracked", hit[0], hit[1]
            e.reason = "sha256 (or artifact bundle sha) has a source_files row"
        entries.append(e)

    # directory -> platform maps from tracked entries
    for e in entries:
        if e.bucket != "tracked":
            continue
        parts = Path(e.rel).parts
        weight = max(e.path.stat().st_size, 1)
        for i in range(1, len(parts)):
            idx.dir_platforms["/".join(parts[:i])][e.platform] += weight
        top = parts[0]
        idx.top_platforms[top][e.platform] += weight
        k = (top, e.platform)
        if k not in idx.top_dates or e.date < idx.top_dates[k]:
            idx.top_dates[k] = e.date

    for e in entries:
        if e.bucket != "unresolved":
            continue
        _classify_untracked(conn, e, idx)

    # a single-product export folder (one dominant platform by bytes) files
    # as one unit: stray rows from older adapters must not scatter its files
    for e in entries:
        if e.bucket not in ("tracked", "companion"):
            continue
        top = Path(e.rel).parts[0]
        plats = idx.top_platforms.get(top)
        if not plats:
            continue
        total = sum(plats.values())
        if sum(1 for w in plats.values() if w / total >= 0.10) < 2:
            dom = plats.most_common(1)[0][0]
            e.platform, e.date = dom, idx.top_dates.get((top, dom)) or e.date

    # byte-identical copies follow the file they duplicate
    by_sha: dict[str, Entry] = {}
    for e in entries:
        if e.bucket in ("tracked", "archive") and not e.reason.startswith("duplicate"):
            by_sha.setdefault(hashing.file_sha256(e.path), e)
    for e in entries:
        if e.bucket == "excluded" and e.reason.startswith("not-conversation-data"):
            twin = by_sha.get(hashing.file_sha256(e.path))
            if twin is not None and twin.path != e.path:
                e.bucket, e.reason = "archive", "duplicate-copy (byte-identical to " + twin.rel + ")"
    return entries


_BUNDLE_CACHE: dict[Path, tuple[str, str] | None] = {}


def _artifact_parent(p: Path, raw_dir: Path) -> Path | None:
    for parent in p.parents:
        if parent == raw_dir or parent == parent.parent:
            return None
        if (parent / "artifact.json").is_file():
            return parent
    return None


_MEDIA_EXT = {".jpg", ".jpeg", ".png", ".heic", ".webp", ".wav", ".mp3", ".mp4", ".mov", ".gif", ".vcf", ".ics", ".pdf"}


def _classify_untracked(conn: sqlite3.Connection, e: Entry, idx: Index) -> None:
    p, rel = e.path, e.rel
    parts = Path(rel).parts
    top = parts[0]
    lowered = [x.lower() for x in parts]

    if p.stat().st_size == 0:
        e.bucket, e.reason = "excluded", "empty-files"
        return

    # the user's own notes at the top of raw/
    if len(parts) == 1 and p.suffix.lower() in {".md", ".txt"}:
        e.bucket, e.reason = "archive", "user-notes (written by the user about raw/, not chat data)"
        return

    # derivative .md/.txt next to an ingested/known .json export of the same stem
    if p.suffix.lower() in {".md", ".txt"}:
        sibling = p.with_suffix(".json")
        if sibling.is_file() and (
            (_tracked_platform(idx, hashing.file_sha256(sibling)) is not None)
            or content_in_vault(conn, sibling)[0]
        ):
            e.bucket, e.reason = "archive", "derivative-markdown (rendering of a .json that is in the vault)"
            return

    # Google Takeout: only the chat-bearing sub-products are ingestable
    if "takeout-collection" == top.lower():
        if "notebooklm" in lowered and "chat history" not in lowered:
            e.bucket, e.reason = "excluded", "notebooklm-documents"
            return
        if len(parts) > 1 and parts[-2] == "Gemini":
            e.bucket, e.reason = "excluded", "gemini-gems-config"
            return
        if "gemini apps" in lowered and not (adapters.detect(p) or (looks_like_chat(p) and not content_in_vault(conn, p)[0] and p.suffix.lower() == ".jsonl")):
            e.bucket, e.reason = "excluded", "gemini-uploaded-attachments"
            return
        if not ({"gemini apps", "ai mode", "gemini in workspace", "chat history"} & set(lowered)) \
                or p.suffix.lower() in _MEDIA_EXT:
            e.bucket, e.reason = "excluded", "google-takeout-non-chat"
            return

    # companion of an ingested single-product export (grok/claude/chatgpt...)
    if top.lower() != "takeout-collection" and not (
        adapters.detect(p) or adapters.detect_projects(p) or adapters.detect_artifacts(p) or looks_like_chat(p)
    ):
        # nearest ancestor directory that holds an ingested file; its dominant
        # platform (by bytes) owns this file as a companion (assets, renders)
        best: tuple[int, str] | None = None
        for i in range(len(parts) - 1, 0, -1):
            plats = idx.dir_platforms.get("/".join(parts[:i]))
            if plats:
                platform, weight = plats.most_common(1)[0]
                if best is None or weight > best[0]:  # ties keep the nearest ancestor
                    best = (weight, platform)
        if best is not None:
            platform = best[1]
            e.bucket, e.platform = "companion", platform
            e.date = idx.top_dates.get((top, platform)) or min(
                (d for (t, pl), d in idx.top_dates.items() if t == top), default=None)
            e.reason = f"sits beside an ingested export file ({platform}); not itself chat data"
            return

    # adapter claims it -> inbox candidate
    claim = adapters.detect(p) or adapters.detect_projects(p) or adapters.detect_artifacts(p)
    if claim is not None:
        e.bucket, e.reason = "candidate", f"adapter {claim.name} claims it"
        return

    # chat-shaped: already in the vault by content, or a genuine backlog item
    if looks_like_chat(p):
        found, ev = content_in_vault(conn, p)
        e.evidence = ev
        if found:
            e.bucket, e.reason = "archive", "derivative-export (every text sample already in the vault)"
        else:
            e.bucket, e.reason = "needs_adapter", "chat-shaped, no adapter claims it, content not in vault"
        return

    e.bucket, e.reason = "excluded", "not-conversation-data"


# ───────────────────────────── destinations ─────────────────────────────


# Container folders that only grouped unrelated exports; their name adds
# nothing once the file sits under <platform>/<date>/.
CONTAINER_DIRS = {"0_archived_zips", "AI_Provider_Exports", "Takeout-Collection"}


def assign_destinations(entries: list[Entry]) -> None:
    for e in entries:
        parts = Path(e.rel).parts
        if len(parts) > 1 and parts[0] in CONTAINER_DIRS:
            parts = parts[1:]
        if _is_lifecycle_path(e.rel):
            continue  # already placed
        if e.bucket == "junk":
            continue
        if e.bucket in ("tracked", "companion"):
            plat = e.platform or "unknown"
            date = e.date or "undated"
            e.dest_rel = "/".join([INGESTED, plat, date, *parts])
        elif e.bucket == "candidate":
            e.dest_rel = "/".join([INBOX, *parts])
        elif e.bucket == "needs_adapter":
            e.dest_rel = "/".join([NEEDS_ADAPTER, *parts])
        elif e.bucket == "excluded":
            e.dest_rel = "/".join([EXCLUDED, e.reason.split(" ")[0], *parts])
        elif e.bucket == "archive":
            slug = e.reason.split(" ")[0]
            e.dest_rel = "/".join([ARCHIVE, "zips" if e.path.suffix.lower() == ".zip" else slug, *parts])


# ───────────────────────────── status file ─────────────────────────────


def _count_files(d: Path) -> int:
    return sum(1 for p in d.rglob("*") if p.is_file() and p.name not in JUNK_NAMES | {"WHY.md"}) if d.is_dir() else 0


def write_status(conn: sqlite3.Connection, raw_dir: Path) -> Path:
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [f"# raw/ status — generated {now}", ""]

    inbox = _count_files(raw_dir / INBOX)
    lines += [f"## {INBOX} — {inbox} files waiting", ""]
    lines += ["Nothing to do." if inbox == 0 else "Run `chatvault intake --apply` to ingest and file them.", ""]

    needs = [p for p in sorted((raw_dir / NEEDS_ADAPTER).rglob("*")) if p.is_file() and p.name not in JUNK_NAMES] \
        if (raw_dir / NEEDS_ADAPTER).is_dir() else []
    flag = "  ⚠ ACTION" if needs else ""
    lines += [f"## {NEEDS_ADAPTER} — {len(needs)} items{flag}", ""]
    if needs:
        for p in needs:
            lines.append(f"- {p.relative_to(raw_dir / NEEDS_ADAPTER)}   (chat-shaped, no adapter claims it)")
    else:
        lines.append("Empty — nothing needs an adapter.")
    lines.append("")

    ing = raw_dir / INGESTED
    lines += [f"## {INGESTED} — {_count_files(ing)} files", ""]
    if ing.is_dir():
        convs = {r["platform"]: (r["n"], r["newest"]) for r in conn.execute(
            "SELECT platform, COUNT(*) n, MAX(started_at) newest FROM v_conversations GROUP BY platform")}
        lines += ["| platform | files | live conversations | newest conversation |", "|---|---|---|---|"]
        for pd in sorted(x for x in ing.iterdir() if x.is_dir()):
            n, newest = convs.get(pd.name, (0, None))
            lines.append(f"| {pd.name} | {_count_files(pd)} | {n} | {(newest or '—')[:10]} |")
        if (ing / "vscode").is_dir() or (ing / "windsurf").is_dir():
            lines += ["", "`vscode/` and `windsurf/` hold the **only copy** of that source data (there is no other raw "
                      "export) — do not treat them as disposable."]
    lines.append("")

    exc = raw_dir / EXCLUDED
    lines += [f"## {EXCLUDED} — {_count_files(exc)} files", ""]
    if exc.is_dir():
        lines += ["| reason | files | why |", "|---|---|---|"]
        for rd in sorted(x for x in exc.iterdir() if x.is_dir()):
            why = rd / "WHY.md"
            body = [x for x in why.read_text().splitlines() if x.strip() and not x.startswith("#")] if why.is_file() else []
            why_line = body[0] if body else "— (no WHY.md)"
            lines.append(f"| {rd.name} | {_count_files(rd)} | {why_line} |")
        lines += ["", "To re-ingest something: move it back to `00_inbox/`."]
    lines.append("")

    arc = raw_dir / ARCHIVE
    lines += [f"## {ARCHIVE} — {_count_files(arc)} files", ""]
    lines += ["Original zips and derivative copies. Never touched automatically.", ""]
    if arc.is_dir() and _count_files(arc):
        lines += ["| kind | files |", "|---|---|"]
        for ad in sorted(x for x in arc.iterdir() if x.is_dir()):
            lines.append(f"| {ad.name} | {_count_files(ad)} |")
    lines.append("")
    out = raw_dir / STATUS_FILE
    out.write_text("\n".join(lines))
    return out


# ───────────────────────────── intake (inbox -> ingested) ─────────────────────────────


@dataclass
class IntakeItem:
    path: Path
    action: str  # moved | would_move | failed | stays | needs_adapter | unclaimed_nonchat | dup_moved
    detail: str = ""
    dest: Path | None = None


def _unique_dest(dest: Path) -> Path:
    if not dest.exists():
        return dest
    stem, suf = dest.stem, dest.suffix
    i = 2
    while True:
        cand = dest.with_name(f"{stem} ({i}){suf}")
        if not cand.exists():
            return cand
        i += 1


def run_intake(conn: sqlite3.Connection, config, *, apply: bool, ingest_fn) -> list[IntakeItem]:
    """Ingest everything in 00_inbox/, verify, then move to 10_ingested/.

    `ingest_fn(path)` ingests one file (or directory) and returns the
    IngestSummary; injected so tests can drive it."""
    raw = config.raw_dir
    inbox = raw / INBOX
    if apply:
        inbox.mkdir(parents=True, exist_ok=True)
    items: list[IntakeItem] = []
    today = datetime.now().strftime("%Y-%m-%d")

    for p in sorted(x for x in inbox.rglob("*") if x.is_file() and x.name not in JUNK_NAMES) if inbox.is_dir() else []:
        mod = adapters.detect(p) or adapters.detect_projects(p) or adapters.detect_artifacts(p)
        if mod is None:
            if looks_like_chat(p):
                dest = _unique_dest(raw / NEEDS_ADAPTER / p.relative_to(inbox))
                if apply:
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(p), str(dest))
                items.append(IntakeItem(p, "needs_adapter", "chat-shaped, no adapter claims it", dest))
            else:
                items.append(IntakeItem(p, "unclaimed_nonchat", "no adapter, not chat-shaped — left in place for you to decide"))
            continue

        if not apply:
            items.append(IntakeItem(p, "would_move", f"adapter {mod.name}"))
            continue

        sha = hashing.file_sha256(p)
        before = conn.execute("SELECT COUNT(*) FROM conversations").fetchone()[0]
        try:
            summary = ingest_fn(p)
        except Exception as exc:  # noqa: BLE001
            items.append(IntakeItem(p, "failed", f"ingest raised: {exc}"))
            continue
        result = summary.files[0] if summary.files else None
        row = conn.execute(
            "SELECT id, platform, status FROM source_files WHERE sha256 = ? ORDER BY id", (sha,)
        ).fetchall()
        if p.name == "artifact.json" and not row:
            row = conn.execute(
                "SELECT id, platform, status FROM source_files WHERE sha256 = ?", (artifact_bundle_sha(p),)
            ).fetchall()
        ok_rows = [r for r in row if r["status"] == "ok"]
        row_sha = sha if conn.execute("SELECT 1 FROM source_files WHERE sha256 = ?", (sha,)).fetchone() else artifact_bundle_sha(p)
        landed = conn.execute("SELECT COUNT(*) FROM conversations").fetchone()[0] - before
        if result is None or result.status == "failed" or not ok_rows:
            items.append(IntakeItem(p, "failed", (result.error if result and result.error else "no source_files row with status ok")))
            continue
        platform = ok_rows[0]["platform"]
        dest = _unique_dest(raw / INGESTED / platform / today / p.relative_to(inbox))
        try:
            dest.parent.mkdir(parents=True, exist_ok=True)
            conn.execute(
                "UPDATE source_files SET path = ?, root_dir = ?, presence = 'present', last_seen_at = ?, "
                "presence_note = ? WHERE sha256 = ?",
                (str(dest.resolve().parent / dest.name), str(raw.resolve()), datetime.now(timezone.utc).isoformat(),
                 f"filed by intake from {INBOX}/{p.relative_to(inbox)}", row_sha),
            )
            shutil.move(str(p), str(dest))
            conn.commit()
        except Exception as exc:  # noqa: BLE001
            conn.rollback()
            if dest.exists() and not p.exists():
                shutil.move(str(dest), str(p))
            items.append(IntakeItem(p, "failed", f"move failed, rolled back: {exc}"))
            continue
        label = "dup_moved" if result.status == "skipped_dup" else "moved"
        items.append(IntakeItem(p, label, f"{result.status}; {landed} new conversation(s)", dest))

    # companions: files that sat beside an ingested aggregate in a dropped folder
    # (assets, renders) are filed with it rather than stranded in the inbox.
    if apply:
        moved_tops: dict[str, Path] = {}
        for it in items:
            if it.action in ("moved", "dup_moved") and it.dest is not None:
                top = it.path.relative_to(inbox).parts[0]
                if len(it.path.relative_to(inbox).parts) > 1:
                    moved_tops[top] = it.dest
        for top, dest in moved_tops.items():
            left = [x for x in (inbox / top).rglob("*") if x.is_file() and x.name not in JUNK_NAMES]
            if any(looks_like_chat(x) or adapters.detect(x) for x in left):
                continue  # something chat-like remains: leave the folder for a human
            plat_dir = raw / INGESTED / dest.relative_to(raw / INGESTED).parts[0] / today
            for x in left:
                tgt = _unique_dest(plat_dir / x.relative_to(inbox))
                tgt.parent.mkdir(parents=True, exist_ok=True)
                shutil.move(str(x), str(tgt))
                items.append(IntakeItem(x, "companion", "filed beside its ingested export", tgt))

    # tidy empty inbox sub-folders (never the inbox itself)
    if apply:
        for d in sorted((x for x in inbox.rglob("*") if x.is_dir()), key=lambda x: -len(x.parts)):
            if not any(d.iterdir()):
                d.rmdir()
        write_status(conn, raw)
    return items


# ───────────────────────────── one-time reorganisation ─────────────────────────────


def plan_summary(entries: list[Entry]) -> dict:
    by_bucket = Counter(e.bucket for e in entries)
    moves = [e for e in entries if e.dest_rel and e.dest_rel != e.rel]
    return {"files": len(entries), "buckets": dict(by_bucket), "moves": len(moves)}


def write_why_files(raw_dir: Path) -> None:
    reasons = {
        "notebooklm-documents": "NotebookLM Sources/Notes/Artifacts — documents the user uploaded or generated, not conversations. Chat Session files from the same Takeout are ingested as platform `notebooklm`.",
        "google-takeout-non-chat": "Google Takeout products that carry no AI conversation (photos, drive, contacts, calendar, activity logs of other Google services).",
        "gemini-uploaded-attachments": "Files the user uploaded into Gemini chats, exported next to the activity JSON. The chats themselves are ingested; these are the attached files.",
        "gemini-gems-config": "Gemini Gems (custom assistants) configuration pages from the Takeout `Gemini/` folder — settings, not conversations.",
        "not-conversation-data": "No adapter claims these and they are not chat-shaped (configs, indexes, scripts, session indexes). Move one back to 00_inbox/ to have it examined again.",
        "empty-files": "Zero-byte files.",
    }
    for slug, why in reasons.items():
        d = raw_dir / EXCLUDED / slug
        if d.is_dir():
            (d / "WHY.md").write_text(f"# {slug}\n\n{why}\n")


def apply_reorganisation(conn: sqlite3.Connection, config, entries: list[Entry]) -> dict:
    """Move every classified file to its destination, journal-first so a
    failure can be undone, then repair source_files paths by content hash
    (reconcile). Nothing is deleted; .DS_Store files stay where they are."""
    from chatvault import reconcile as reconcile_mod

    raw = config.raw_dir
    journal: list[tuple[Path, Path]] = []
    try:
        for e in entries:
            if not e.dest_rel or e.dest_rel == e.rel:
                continue
            dst = raw / e.dest_rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if dst.exists():
                raise FileExistsError(f"destination exists: {dst}")
            shutil.move(str(e.path), str(dst))
            journal.append((e.path, dst))
    except Exception:
        for src, dst in reversed(journal):
            src.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(dst), str(src))
        raise
    # drop now-empty source folders (never raw/ itself or lifecycle folders)
    for d in sorted((x for x in raw.rglob("*") if x.is_dir()), key=lambda x: -len(x.parts)):
        rel = d.relative_to(raw).parts
        if rel[0] in LIFECYCLE_DIRS:
            continue
        if not any(c.name not in JUNK_NAMES for c in d.iterdir()):
            for c in d.iterdir():
                c.unlink()
            d.rmdir()
    for name in LIFECYCLE_DIRS:
        (raw / name).mkdir(exist_ok=True)
    write_why_files(raw)
    report = reconcile_mod.reconcile(conn, kind="all", search_dirs=[raw])
    write_status(conn, raw)
    return {
        "moved_files": len(journal),
        "reconcile": {"checked": report.checked, "moved": report.moved, "missing": len(report.missing),
                      "changed": report.changed},
    }


def write_plan_report(entries: list[Entry], out: Path, *, raw_dir: Path, extra_notes: str = "") -> None:
    """Human-readable migration plan (per source folder, not per file) plus a
    CSV beside raw/ with every file's proposed destination."""
    today = datetime.now().strftime("%Y-%m-%d")
    lines = [f"# raw/ migration plan — {today}", ""]
    lines += [
        "Derived by `chatvault intake --reorganise` (dry run): every file under `raw/` is classified by the",
        "rule in `src/chatvault/intake.py` — sha256 tracked → companion of an ingested export → content already",
        "in the vault → adapter claims it → chat-shaped but unclaimed → excluded with a reason. Nothing here",
        "was hand-assigned. Counts are files, not conversations.", "",
    ]
    tot = Counter(e.bucket for e in entries)
    lines += ["## Totals", "", "| bucket | files | goes to |", "|---|---|---|"]
    goes = {
        "tracked": INGESTED, "companion": f"{INGESTED} (beside its export)", "archive": ARCHIVE,
        "excluded": EXCLUDED, "candidate": INBOX, "needs_adapter": NEEDS_ADAPTER, "junk": "stays (Finder metadata)",
    }
    for b in ("tracked", "companion", "candidate", "needs_adapter", "excluded", "archive", "junk"):
        lines.append(f"| {b} | {tot.get(b, 0)} | {goes[b]} |")
    lines += ["", f"Total files: {len(entries)}", ""]

    lines += ["## Per source folder", "", "| current folder | files | → destination | why |", "|---|---|---|---|"]
    groups: dict[tuple[str, str], list[Entry]] = defaultdict(list)
    for e in entries:
        top = Path(e.rel).parts[0] if len(Path(e.rel).parts) > 1 else "(raw root)"
        dest = "stays"
        if e.dest_rel:
            dp = Path(e.dest_rel).parts
            dest = "/".join(dp[:3] if dp[0] == INGESTED else dp[:2])
        groups[(top, f"{e.bucket}→{dest}")].append(e)
    for (top, key), es in sorted(groups.items()):
        bucket, dest = key.split("→", 1)
        why = Counter(x.reason.split(" (")[0] for x in es).most_common(1)[0][0]
        lines.append(f"| `{top}` | {len(es)} | `{dest}` | {bucket}: {why} |")
    lines.append("")

    ev = [e for e in entries if e.evidence]
    if ev:
        lines += ["## Chat-shaped files whose text is already in the vault", "",
                  "Tested by looking real text from the file up in the vault's full-text index (not by name or path):", ""]
        for e in ev:
            lines.append(f"- `{e.rel}` — {e.evidence} → {e.bucket}")
        lines.append("")
    if extra_notes:
        lines += [extra_notes, ""]
    out.write_text("\n".join(lines))

    csv = raw_dir.parent / "logs" / "raw_migration_plan.csv"
    csv.parent.mkdir(exist_ok=True)
    with csv.open("w") as fh:
        fh.write("current,bucket,platform,destination,reason\n")
        for e in entries:
            fh.write(",".join('"' + str(v or "").replace('"', "'") + '"' for v in (e.rel, e.bucket, e.platform, e.dest_rel or "(stays)", e.reason)) + "\n")
